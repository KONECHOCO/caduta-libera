class I18nManager {
  constructor() {
    this.currentLang = 'it';
    // Auto-detect browser language if available
    const browserLang = navigator.language ? navigator.language.slice(0, 2).toLowerCase() : 'it';
    if (TRANSLATIONS[browserLang]) {
      this.currentLang = browserLang;
    }
    try {
      const saved = localStorage.getItem('trap10.lang');
      if (TRANSLATIONS[saved]) this.currentLang = saved;
    } catch {}
    this.listeners = [];
  }

  setLanguage(lang) {
    if (TRANSLATIONS[lang]) {
      this.currentLang = lang;
      try { localStorage.setItem('trap10.lang', lang); } catch {}
      this.notify();
    }
  }

  getLanguage() {
    return this.currentLang;
  }

  t(key, params = {}) {
    let str = TRANSLATIONS[this.currentLang]?.[key] || TRANSLATIONS['it'][key] || key;
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
    }
    return str;
  }

  onLanguageChange(callback) {
    this.listeners.push(callback);
  }

  notify() {
    this.listeners.forEach(cb => cb(this.currentLang));
  }
}

export const i18n = new I18nManager();
